"""Outbound notifications to Slack, Microsoft Teams and HTTPS webhooks.

- Events are queued in the same transaction as the change that caused them (so a rolled-back change sends nothing)
  and delivered every minute by the outbound job, with retries after 1, 5, 30, 120 and 720 minutes.
- Content is minimal: event, reference, title, severity and a link back to Keystone. Incidents send their reference
  and severity only, not their title: chat channels are a wider audience than the incident register.
- Destinations: Slack incoming webhooks (hooks.slack.com), Teams Workflows or legacy connector webhooks
  (*.webhook.office.com, *.logic.azure.com, *.environment.api.powerplatform.com), and any public HTTPS endpoint for
  webhooks. Webhook URLs go through the same checks as self-hosted connectors: HTTPS, public address (or the
  operator's KEYSTONE_INTEGRATION_PRIVATE_HOSTS), pinned connection, no redirects, response size cap.
- Webhooks are signed: header X-Keystone-Signature: t=<unix time>,v1=<hex HMAC-SHA256(secret, "<t>.<body>")>.
  The secret is generated by Keystone, shown once and stored encrypted.
- URLs are secrets (Slack and Teams embed their token): encrypted, write-only, shown as the host only, and delivery
  errors never include the URL's path or query.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import secrets as pysecrets
import time
import uuid
from datetime import datetime, timedelta
from urllib.parse import urlparse

from sqlalchemy import select
from sqlalchemy.orm import Session

from keystone.core import secrets as crypto
from keystone.core.db import utcnow
from keystone.core.services import authorize, get_or_404, require_text
from keystone.core.settings import get_settings
from keystone.integrations.http import Api, ConnectorError, HostPolicy

from .models import KINDS, Delivery, Destination

EVENTS = {
    "incident.created": "Incident reported",
    "finding.opened": "Critical or high attack surface finding",
    "vulnerability.known_exploited": "Known-exploited vulnerability found",
    "external.issue": "Critical or high internet-facing issue",
    "system.alert": "System health problem",
    "policy.approved": "Policy version approved",
    "access_review.completed": "Access review completed",
    "config.failed": "Critical or high configuration baseline failure",
}
POLICIES = {
    "slack": HostPolicy(hosts=frozenset({"hooks.slack.com"})),
    "teams": HostPolicy(suffixes=(".webhook.office.com", ".logic.azure.com", ".environment.api.powerplatform.com")),
    "webhook": HostPolicy(self_hosted=True),
}
BACKOFF_MINUTES = (1, 5, 30, 120, 720)
MAX_DESTINATIONS = 20
SIGNATURE_HEADER = "X-Keystone-Signature"


def _check_url(kind: str, url: str) -> str:
    p = urlparse((url or "").strip())
    host = (p.hostname or "").lower()
    if p.scheme != "https" or p.username or p.password or p.port not in (None, 443) or not host or len(url) > 2000:
        raise ValueError("Enter the full https:// URL (no user name, password or port).")
    if not POLICIES[kind].allows(host):
        raise ValueError({"slack": "Slack webhook URLs start with https://hooks.slack.com/.",
                          "teams": "Use the webhook URL from a Teams Workflow (or a connector on webhook.office.com)."}.get(kind, f"{host} isn't a valid host."))
    return host


def destinations(session: Session, actor) -> list[Destination]:
    authorize(session, actor, "integration.manage")
    return list(session.scalars(select(Destination).order_by(Destination.name)))


def save_destination(session: Session, actor, destination_id: int | None = None, *, kind: str | None = None, name: str | None = None, url: str | None = None,
                     events: list[str] | None = None, enabled: bool | None = None) -> tuple[Destination, str | None]:
    """Create or update. Returns (destination, signing secret if one was just created: shown once)."""
    authorize(session, actor, "integration.manage")
    new_secret = None
    if destination_id:
        d = get_or_404(session, Destination, destination_id)
    else:
        if kind not in KINDS:
            raise ValueError("Choose Slack, Teams or webhook.")
        if not url:
            raise ValueError("Enter the URL.")
        if len(list(session.scalars(select(Destination.id)))) >= MAX_DESTINATIONS:
            raise ValueError(f"At most {MAX_DESTINATIONS} destinations.")
        d = Destination(kind=kind, events=[], enabled=True, url_enc="", url_host="")
        if kind == "webhook":
            new_secret = "whsec_" + pysecrets.token_urlsafe(32)
            d.signing_secret_enc = crypto.encrypt(new_secret)
    if name is not None:
        d.name = require_text(name, "Name")[:100]
    if url:
        d.url_host = _check_url(d.kind, url)
        d.url_enc = crypto.encrypt(url.strip())
    if events is not None:
        unknown = set(events) - set(EVENTS)
        if unknown or not events:
            raise ValueError("Choose at least one event from the list.")
        d.events = sorted(set(events))
    if enabled is not None:
        d.enabled = enabled
    if not d.name:
        raise ValueError("Name is required.")
    session.add(d)
    session.flush()
    return d, new_secret


def delete_destination(session: Session, actor, destination_id: int) -> None:
    authorize(session, actor, "integration.manage")
    session.delete(get_or_404(session, Destination, destination_id))
    session.flush()


def emit(session: Session, event: str, *, title: str, detail: str = "", severity: str | None = None, ref: str | None = None, page: str = "/") -> int:
    """Queue an event for every enabled destination that wants it. Returns how many deliveries were queued."""
    if event not in EVENTS:
        raise ValueError(f"unknown event {event}")
    dests = [d for d in session.scalars(select(Destination).where(Destination.enabled.is_(True))) if event in (d.events or [])]
    if not dests:
        return 0
    base = get_settings().public_url
    data = {"title": title[:300], "detail": detail[:1000], "severity": severity, "ref": ref, "url": f"{base}{page}" if base else None, "path": page}
    now = utcnow()
    for d in dests:
        session.add(Delivery(uid=str(uuid.uuid4()), destination_id=d.id, event=event, payload=data, status="pending", attempts=0, next_attempt_at=now, created_at=now))
    session.flush()
    return len(dests)


def test_destination(session: Session, actor, destination_id: int) -> Delivery:
    authorize(session, actor, "integration.manage")
    d = get_or_404(session, Destination, destination_id)
    now = utcnow()
    dl = Delivery(uid=str(uuid.uuid4()), destination_id=d.id, event="test", payload={"title": "Test message from Keystone", "detail": "If you can read this, the destination works.",
                                                                                     "severity": None, "ref": None, "url": None, "path": "/"},
                  status="pending", attempts=0, next_attempt_at=now, created_at=now)
    session.add(dl)
    session.flush()
    _deliver(session, d, dl)
    return dl


