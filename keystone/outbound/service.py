def _escape_slack(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def body_for(d: Destination, dl: Delivery) -> dict:
    p = dl.payload
    label = EVENTS.get(dl.event, "Test")
    head = f"{label}: {p['title']}" if dl.event != "test" else p["title"]
    if d.kind == "slack":
        text = f"*{_escape_slack(head)}*"
        if p.get("detail"):
            text += f"\n{_escape_slack(p['detail'])}"
        if p.get("url"):
            text += f"\n<{p['url']}|Open in Keystone>"
        return {"text": text}
    if d.kind == "teams":
        card = {"type": "AdaptiveCard", "$schema": "http://adaptivecards.io/schemas/adaptive-card.json", "version": "1.4",
                "body": [{"type": "TextBlock", "text": head, "weight": "Bolder", "wrap": True}] + ([{"type": "TextBlock", "text": p["detail"], "wrap": True}] if p.get("detail") else [])}
        if p.get("url"):
            card["actions"] = [{"type": "Action.OpenUrl", "title": "Open in Keystone", "url": p["url"]}]
        return {"type": "message", "attachments": [{"contentType": "application/vnd.microsoft.card.adaptive", "content": card}]}
    return {"id": dl.uid, "event": dl.event, "created_at": dl.created_at.isoformat() + "Z", "data": p}


def sign(secret: str, body: bytes, ts: int) -> str:
    return f"t={ts},v1=" + hmac.new(secret.encode(), f"{ts}.".encode() + body, hashlib.sha256).hexdigest()


def _deliver(session: Session, d: Destination, dl: Delivery) -> None:
    url = crypto.decrypt(d.url_enc)
    raw = json.dumps(body_for(d, dl), separators=(",", ":")).encode()
    headers = {"Content-Type": "application/json", "Accept": "*/*"}
    if d.kind == "webhook":
        headers |= {"X-Keystone-Event": dl.event, "X-Keystone-Delivery": dl.uid,
                    SIGNATURE_HEADER: sign(crypto.decrypt(d.signing_secret_enc or ""), raw, int(time.time()))}
    dl.attempts += 1
    try:
        Api(POLICIES[d.kind]).request("POST", url, headers=headers, content=raw, retries=0)
    except ConnectorError as e:
        parsed = urlparse(url)
        msg = str(e)
        for secret_part in (parsed.path, parsed.query):  # Slack and Teams URLs carry their token
            if secret_part:
                msg = msg.replace(secret_part, "…")
        dl.last_error = msg[:300]
        if dl.attempts > len(BACKOFF_MINUTES) or dl.event == "test":
            dl.status = "failed"
        else:
            dl.next_attempt_at = utcnow() + timedelta(minutes=BACKOFF_MINUTES[dl.attempts - 1])
        d.last_status, d.last_error = "error", dl.last_error
        session.flush()
        return
    dl.status, dl.sent_at, dl.last_error = "sent", utcnow(), None
    d.last_status, d.last_error, d.last_sent_at = "ok", None, dl.sent_at
    session.flush()


def deliver_due(session: Session, now: datetime | None = None, limit: int = 100) -> dict:
    now = now or utcnow()
    out = {"sent": 0, "failed": 0, "retry": 0}
    for dl in list(session.scalars(select(Delivery).where(Delivery.status == "pending", Delivery.next_attempt_at <= now).order_by(Delivery.id).limit(limit))):
        d = session.get(Destination, dl.destination_id)
        if d is None or not d.enabled:
            dl.status = "cancelled"
            continue
        _deliver(session, d, dl)
        out["sent" if dl.status == "sent" else "failed" if dl.status == "failed" else "retry"] += 1
    cutoff = now - timedelta(days=30)  # keep a month of delivery history
    for old in session.scalars(select(Delivery).where(Delivery.created_at < cutoff, Delivery.status != "pending")):
        session.delete(old)
    session.flush()
    return out


def recent(session: Session, actor, destination_id: int, limit: int = 50) -> list[Delivery]:
    authorize(session, actor, "integration.manage")
    return list(session.scalars(select(Delivery).where(Delivery.destination_id == destination_id).order_by(Delivery.id.desc()).limit(limit)))
